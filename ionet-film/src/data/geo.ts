const inPoly = (lon: number, lat: number, poly: P) => {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};

export const isLand = (lon: number, lat: number) => {
  if (lat < -70) return true;
  if (WATER.some((p) => inPoly(lon, lat, p))) return false;
  return LAND.some((p) => inPoly(lon, lat, p));
};

